// Helper to get products for a specific category slug or query
export function getProductsForCategory(categorySlug: string): Product[] {
  const normSlug = categorySlug.toLowerCase().trim();
  return ALL_PRODUCTS.filter((p) => {
    const mainSlug = (p.category_main || '').toLowerCase();
    const catName = (p.category || '').toLowerCase();
    return mainSlug === normSlug || catName.includes(normSlug) || normSlug.includes(mainSlug);
  });
}

export function getCategoryBySlug(slug: string): CategoryData | undefined {
  const norm = slug.toLowerCase().trim();
  return CATALOG_CATEGORIES.find((c) => c.slug === norm);
}

export function getProductById(id: string | number): Product | undefined {
  const strId = String(id).toLowerCase();
  return ALL_PRODUCTS.find((p) => String(p.id).toLowerCase() === strId || (p.reference && p.reference.toLowerCase() === strId));
}
